String appT(String key, {String? code}) {
  final activeCode = (code ?? appLocale.value.languageCode).split('_').first;
  return appTranslations[activeCode]?[key] ??
      appTranslations['fr']?[key] ??
      key;
}

String appTC(BuildContext context, String key) {
  return appT(key, code: Localizations.localeOf(context).languageCode);
}

String appIntlLocale(String code) {
  return switch (code.split('_').first) {
    'en' => 'en_US',
    'es' => 'es_ES',
    'ar' => 'ar',
    'pt' => 'pt_PT',
    _ => 'fr_FR',
  };
}
